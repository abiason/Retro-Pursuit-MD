"""Original code-native hazard tiles, ordered in SGDK sprite columns."""
from pathlib import Path

shapes = [
    ['0000004400000000', '0000045540000000', '0000445544000000', '0004444444400000',
     '0044555555440000', '0444444444440000', '4444444444444000', '7777777777777777'],
    ['0066666666666600', '0444444444444440', '0455455455455440', '0444444444444440',
     '0444444444444440', '0777777777777770', '0077000000007700', '0077000000007700'],
    ['00444400', '04555440', '45565544', '45666554',
     '45565554', '44555544', '04444440', '00444400'],
]
words = []
for rows in shapes:
    assert len(rows) == 8 and all(len(row) == len(rows[0]) for row in rows)
    for column in range(len(rows[0]) // 8):
        words.extend('0x' + row[column*8:column*8+8] for row in rows)
text = '/* Generated by tools/generate_obstacles.py; original Retro Pursuit art. */\n'
text += 'static const u32 obstacle_tiles[40] = {\n'
text += ''.join('    ' + ', '.join(words[i:i+8]) + ',\n' for i in range(0, len(words), 8))
text += '};\n'
Path('src/platform/obstacle_tiles.h').write_text(text)
