legs = [
    ['0000122222100000', '0000122122100000', '0000122122100000', '0000122122100000',
     '0000122122100000', '0000122122100000', '0000111011100000', '0001111011110000'],
    ['0000122222100000', '0001222122100000', '0012221012210000', '0012210001221000',
     '0012210000122100', '0011100000011100', '0111100000011110', '0000000000000000'],
    ['0000122222100000', '0000122122210000', '0001221012221000', '0012210001221000',
     '0122100001221000', '0111000000111000', '1111000000111100', '0000000000000000'],
    ['0000122222100000', '0001222222210000', '0012221122221000', '0012210012221000',
     '0011100001111000', '0111100000000000', '0000000000000000', '0000000000000000'],
]
def write_tiles(name, head_rows, body_rows, uniform):
    def colored(rows):
        return [row.replace('6', uniform) for row in rows]
    walk_legs = [row.replace('2', uniform) for rows in legs for row in rows]
    poses = [(head_rows + body_rows + walk_legs[i*8:i*8+8]) for i in range(4)]
    back_head = colored([
        '0000011111100000', '0000166666610000', '0001666666661000', '0001666666661000',
        '0000166666100000', '0000155555100000', '0000155555100000', '0000015551000000'])
    climb_body = colored([
        '0011100000011100', '0015116666115100', '0015166666155100', '0001666666661000',
        '0000166666100000', '0000166666100000', '0001111111110000', '0000166666100000'])
    poses += [back_head + climb_body + walk_legs[8:16], back_head + climb_body + walk_legs[16:24]]
    salute = colored([
        '0110116666110110', '0151167766111510', '0015167766151000', '0015166666151000',
        '0001666666661000', '0000166666100000', '0001111111110000', '0000166666100000'])
    hurt = colored([
        '0000116666110000', '0111666666661000', '0151167766151000', '0015166666111110',
        '0001666666661510', '0000166666101110', '0001111111110000', '0000166666100000'])
    poses += [head_rows + salute + walk_legs[:8], head_rows + hurt + walk_legs[16:24]]
    words = []
    for rows in poses:
        assert len(rows) == 24 and all(len(row) == 16 for row in rows)
        for column in range(2):
            for tile_y in range(3):
                words.extend('0x' + row[column*8:column*8+8] for row in rows[tile_y*8:tile_y*8+8])
    output = '/* Generated by tools/generate_player.py; original Retro Pursuit art. */\n'
    output += f'static const u32 {name}_tiles[384] = {{\n'
    output += ''.join('    ' + ', '.join(words[i:i+8]) + ',\n' for i in range(0, len(words), 8))
    output += '};\n'
    Path(f'src/platform/{name}_tiles.h').write_text(output)

