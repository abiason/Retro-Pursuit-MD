"""Original 5x7 letterforms expanded into a 128x48 code-native tile logo."""
from pathlib import Path

glyphs = {
    'R': ['11110','10001','10001','11110','10100','10010','10001'],
    'E': ['11111','10000','10000','11110','10000','10000','11111'],
    'T': ['11111','00100','00100','00100','00100','00100','00100'],
    'O': ['01110','10001','10001','10001','10001','10001','01110'],
    'P': ['11110','10001','10001','11110','10000','10000','10000'],
    'U': ['10001','10001','10001','10001','10001','10001','01110'],
    'S': ['01111','10000','10000','01110','00001','00001','11110'],
    'I': ['11111','00100','00100','00100','00100','00100','11111'],
}
pixels = [[0] * 128 for _ in range(48)]
for text, top in [('RETRO', 1), ('PURSUIT', 25)]:
    left = (128 - (len(text) * 18 - 3)) // 2
    for shadow in (True, False):
        for i, letter in enumerate(text):
            for y, row in enumerate(glyphs[letter]):
                for x, filled in enumerate(row):
                    if filled == '0': continue
                    for dy in range(3):
                        for dx in range(3):
                            px = left + i*18 + x*3 + dx + (2 if shadow else 0)
                            py = top + y*3 + dy + (2 if shadow else 0)
                            pixels[py][px] = 6 if shadow else (3 if y < 2 else 2)
words = []
for tile_y in range(6):
    for tile_x in range(16):
        for row in pixels[tile_y*8:tile_y*8+8]:
            words.append('0x' + ''.join(format(value, 'X') for value in row[tile_x*8:tile_x*8+8]))
output = '/* Generated by tools/generate_logo.py; original Retro Pursuit lettering. */\n'
output += 'static const u32 logo_tiles[768] = {\n'
output += ''.join('    ' + ', '.join(words[i:i+8]) + ',\n' for i in range(0,len(words),8))
output += '};\n'
Path('src/platform/logo_tiles.h').write_text(output)
